alien_color = "green"

if alien_color == "green":
    print("You earned 5 points for shooting the alien")
else:
    print("You earned 10 points for shooting the alien")

alien_color = "yellow"
if alien_color == "green":
    print("You earned 5 points for shooting the alien")
else:
    print("You earned 10 points for shooting the alien")
